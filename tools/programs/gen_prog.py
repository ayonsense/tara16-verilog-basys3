"""
Assemble a TARA .tara program into:
  boot.hex          : one 16-bit word per line ($readmemh into memory.v, big-endian)
  boot_expected.vh  : expected final register state (from the golden simulator),
                      included by sim/tb_cpu.v for self-checking.

Usage:
  python3 gen_prog.py [path/to/program.tara]
Defaults to the bundled Fibonacci demo. TARA16_PROG_OUT selects the output directory.
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SIM  = os.path.abspath(os.environ.get("TARA16_SIM") or os.path.join(HERE, "..", "..", "..", "tara16-studio"))
sys.path.insert(0, SIM)
from src.assembler.asm import assemble
from src.simulation.cpu import TaraCPU

DEFAULT = os.path.join(SIM, "src/examples/progs/Basic/fibonacci.tara")
OUTPUT = os.path.abspath(os.environ.get("TARA16_PROG_OUT") or HERE)

def main():
    os.makedirs(OUTPUT, exist_ok=True)
    path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT
    with open(path) as f:
        src = f.read()
    words, listing, errors, labels = assemble(src)
    if errors:
        for e in errors: print("ASM ERROR:", e)
        sys.exit(1)

    # boot.hex — one 16-bit WORD per line (memory.v is 1024 x 16, $readmemh words)
    with open(os.path.join(OUTPUT, "boot.hex"), "w") as f:
        for _, w in words:
            f.write(f"{w & 0xFFFF:04x}\n")

    # golden expected final state
    g = TaraCPU(); g.load_program([w for _, w in words])
    n = 0
    while not g.halted and n < 2_000_000:
        g.step(record_history=False); n += 1

    with open(os.path.join(OUTPUT, "boot_expected.vh"), "w") as f:
        f.write("// AUTO-GENERATED by gen_prog.py — expected final register state\n")
        f.write(f"// program: {os.path.basename(path)}   golden_instr={g.instr_count}\n")
        for i in range(8):
            f.write(f"localparam [15:0] EXP_R{i} = 16'h{g.reg[i] & 0xFFFF:04X};\n")
        f.write(f"localparam EXP_HALTED = 1'b{1 if g.halted else 0};\n")

    print(f"program : {os.path.basename(path)}")
    print(f"words   : {len(words)}  (boot.hex = {2*len(words)} bytes)")
    print(f"golden  : {'halted' if g.halted else 'NOT halted'} after {g.instr_count} instr")
    print("regs    : " + " ".join(f"R{i}={g.reg[i]&0xFFFF:#06x}" for i in range(8)))

if __name__ == "__main__":
    main()
